// Writes the building catalogue as SQL for Supabase (ids, era, country, architects, themes), so the
// database can check synced progress and award badges.
//   node scripts/make-supabase-buildings.mjs      (from frontend/, after buildings.json changes)
// The file can be run again at any time (SQL editor or `supabase db push` on a fresh project): it only
// adds and updates rows. A test (src/social/sql.test.js) fails when it is out of date.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const buildingsSqlFile = join(root, 'supabase/migrations/20261113000002_buildings_data.sql')

const text = (value) => `'${String(value).replaceAll("'", "''")}'`
const list = (values) => `array[${values.map(text).join(', ')}]::text[]`

export function buildingsSql() {
  const buildings = JSON.parse(readFileSync(join(root, 'src/main/resources/data/buildings.json'), 'utf8'))
  const rows = buildings
    .map((b) => `  (${text(b.id)}, ${text(b.era)}, ${text(b.location.countryCode)}, ${list(b.architects.map((a) => a.name))}, ${list(b.themes ?? [])})`)
    .join(',\n')
  return `-- Generated by frontend/scripts/make-supabase-buildings.mjs from buildings.json. Do not edit by hand.
insert into public.buildings (id, era, country, architects, themes) values
${rows}
on conflict (id) do update set era = excluded.era, country = excluded.country, architects = excluded.architects, themes = excluded.themes;
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(buildingsSqlFile, buildingsSql())
