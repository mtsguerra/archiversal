#!/usr/bin/env python3
"""Writes src/game/features.js: for each building, the visible features its English text mentions
(a dome, a tower...). The Library's feature search reads it. Rerun after adding buildings."""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
FEATURES = {
    'dome': r'\bdomes?\b|\bdomed\b|\bcupola',
    'tower': r'\btowers?\b|\bbell tower|\bcampanile|\bskyscraper',
    'spire': r'\bspires?\b|\bsteeple|\bpinnacle|\bminaret',
    'columns': r'\bcolumns?\b|\bcolonnade|\bpillars?\b|\bportico|\bpilasters?\b',
    'arches': r'\barch(es)?\b|\barcade|\barched',
    'vault': r'\bvault(s|ed|ing)?\b|\bribbed',
    'glass': r'\bglass\b|\bglazed|\bglazing|\bcurtain wall|\bstained',
    'concrete': r'\bconcrete\b|\bbrutalis',
    'courtyard': r'\bcourtyards?\b|\bcloisters?\b|\batrium|\bgardens?\b',
    'sculpture': r'\bsculpt|\bstatues?\b|\bfrieze|\brelief|\bgargoyle',
}
def texts(b):
    out = [b['name']]
    s = b.get('summary') or {}
    out.append(s.get('description') or '')
    out += s.get('keyFeatures') or []
    out += s.get('funFacts') or []
    out += [h.get('text') or '' for h in b.get('hints', [])]
    for d in b.get('drawings', []) + b.get('photos', []):
        out += [d.get('alt') or '', d.get('caption') or '']
    return ' '.join(x for x in out if isinstance(x, str)).lower()

data = json.load(open(ROOT / 'src/main/resources/data/buildings.json'))
res = {}
for b in data:
    t = texts(b)
    found = [k for k, rx in FEATURES.items() if re.search(rx, t)]
    if found:
        res[b['id']] = found
lines = ['// Generated by scripts/make-features.py: the features each building is known for, from its English text.',
         'export const FEATURES = ' + json.dumps(list(FEATURES)) .replace('"', "'") + '',
         'export const FEATURES_OF = {']
for k in sorted(res):
    lines.append(f"  '{k}': {json.dumps(res[k])},".replace('"', "'"))
lines.append('}')
(ROOT / 'frontend/src/game/features.js').write_text('\n'.join(lines) + '\n')
from collections import Counter
print(len(res), Counter(f for v in res.values() for f in v))
